-- ---------- Rôles ----------
create type public.app_role as enum ('admin');

create table public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.app_role not null,
  unique (user_id, role)
);
alter table public.user_roles enable row level security;

create or replace function public.is_admin(_uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.user_roles where user_id = _uid and role = 'admin')
$$;

create policy "roles own read" on public.user_roles for select to authenticated using (user_id = auth.uid() or public.is_admin());

-- ---------- Membres (fiches, avec ou sans compte) ----------
create table public.members (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete set null,
  member_number integer generated by default as identity unique,
  email text unique,
  first_name text not null default '',
  last_name text not null default '',
  phone text not null default '',
  country text not null default 'FR' check (country in ('FR','CD')),
  city text not null default '',
  category text not null default 'sympathisant' check (category in ('effectif','sympathisant')),
  pole text not null default '',
  status text not null default 'pending' check (status in ('pending','validated','refused','founder')),
  founder boolean not null default false,
  accepted_statutes_at timestamptz,
  rgpd_consent_at timestamptz,
  documents_consent_at timestamptz,
  validated_at timestamptz,
  created_at timestamptz not null default now()
);
alter table public.members enable row level security;

create or replace function public.my_member_id()
returns uuid language sql stable security definer set search_path = public as $$
  select id from public.members where user_id = auth.uid()
$$;

create or replace function public.is_validated(_uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members where user_id = _uid and status = 'validated')
$$;

create policy "members admin" on public.members for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "members own read" on public.members for select to authenticated using (user_id = auth.uid());
create policy "members own update" on public.members for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Un membre ne peut modifier que ses coordonnées, pas son statut
create or replace function public.protect_member_fields()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then
    new.status := old.status; new.founder := old.founder; new.user_id := old.user_id;
    new.email := old.email; new.member_number := old.member_number; new.validated_at := old.validated_at;
    new.category := old.category;
  end if;
  if new.status = 'validated' and old.status is distinct from 'validated' then new.validated_at := now(); end if;
  return new;
end $$;
create trigger trg_protect_member before update on public.members for each row execute function public.protect_member_fields();

-- Consentement pour le dépôt de documents
create or replace function public.consent_documents()
returns void language sql security definer set search_path = public as $$
  update public.members set documents_consent_at = coalesce(documents_consent_at, now()) where user_id = auth.uid();
$$;
revoke all on function public.consent_documents() from public, anon;
grant execute on function public.consent_documents() to authenticated;

-- Création de compte : relie la fiche existante (même email) ou crée une fiche "en attente".
-- L'adresse de l'administratrice reçoit automatiquement le rôle admin.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb); mid uuid;
begin
  select id into mid from public.members where lower(email) = lower(new.email) and user_id is null;
  if mid is null then
    insert into public.members(user_id, email, first_name, last_name, phone, country, city, category, pole, accepted_statutes_at, rgpd_consent_at)
    values (new.id, lower(new.email),
      left(coalesce(m->>'first_name',''),150), left(coalesce(m->>'last_name',''),150), left(coalesce(m->>'phone',''),40),
      case when m->>'country' = 'CD' then 'CD' else 'FR' end, left(coalesce(m->>'city',''),150),
      case when m->>'category' = 'effectif' then 'effectif' else 'sympathisant' end, left(coalesce(m->>'pole',''),150),
      case when m->>'accept_statutes' = 'true' then now() end, case when m->>'rgpd' = 'true' then now() end);
  else
    update public.members set user_id = new.id,
      phone = case when phone = '' then left(coalesce(m->>'phone',''),40) else phone end,
      city = case when city = '' then left(coalesce(m->>'city',''),150) else city end,
      accepted_statutes_at = coalesce(accepted_statutes_at, case when m->>'accept_statutes' = 'true' then now() end),
      rgpd_consent_at = coalesce(rgpd_consent_at, case when m->>'rgpd' = 'true' then now() end)
    where id = mid;
  end if;
  if lower(new.email) = 'ADRESSE_ADMIN@exemple.com' /* remplacée dans la base par l'adresse réelle */ then
    insert into public.user_roles(user_id, role) values (new.id, 'admin') on conflict do nothing;
    update public.members set status = 'validated', validated_at = coalesce(validated_at, now()) where user_id = new.id;
  end if;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

-- ---------- Documents des membres ----------
create table public.member_files (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.members(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 150),
  category text not null default 'document' check (category in ('identity','card','document')),
  year integer not null default extract(year from now())::int check (year between 1950 and 2200),
  file_path text not null unique,
  created_at timestamptz not null default now()
);
alter table public.member_files enable row level security;
create policy "files admin" on public.member_files for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "files own read" on public.member_files for select to authenticated using (member_id = public.my_member_id());
create policy "files own insert" on public.member_files for insert to authenticated with check (
  member_id = public.my_member_id() and public.is_validated()
  and exists (select 1 from public.members where id = member_id and documents_consent_at is not null)
  and split_part(file_path, '/', 1) = member_id::text);

