  method text not null default '' check (char_length(method) <= 50),
  reference text not null default '' check (char_length(reference) <= 120),
  status text not null default 'pending' check (status in ('pending','validated','refused')),
  created_at timestamptz not null default now()
);
alter table public.payments enable row level security;
create policy "payments admin" on public.payments for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "payments own read" on public.payments for select to authenticated using (member_id = public.my_member_id());
create policy "payments own insert" on public.payments for insert to authenticated with check (member_id = public.my_member_id() and status = 'pending');

